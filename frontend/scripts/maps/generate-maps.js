const { createHash } = require('node:crypto');
const fs = require('node:fs/promises');
const path = require('node:path');
const sharp = require('sharp');

const MAPS_DIRECTORY = path.resolve(__dirname, '../../src/assets/images/maps');
const BUDGET_BYTES = 4466801;
const MAPS = [
  { id: 'art', file: 'mappa_art.png', width: 2816, height: 1536, sha256: '24616aa4ab4c5acc5189cd03d146129ae9ce4f216275d6ac772247ce41168452' },
  { id: 'precisa', file: 'mappa_precisa.png', width: 2752, height: 1536, sha256: 'e53ad9b884877865d0786058c6fcbd7801fb62014c3eba14142dc9bf6828360e' },
];
const DIVISORS = [4, 2, 1];
const SETTINGS = {
  resize: { kernel: 'lanczos3', fit: 'fill' },
  avif: { quality: 85, effort: 6, chromaSubsampling: '4:4:4' },
  webp: { quality: 96, effort: 6, smartSubsample: true },
};
const sha256 = (bytes) => createHash('sha256').update(bytes).digest('hex');

function sourceModule(manifest) {
  const imports = ['// Generated by npm run maps:generate. Do not edit.'];
  const entries = [];
  for (const [id, map] of Object.entries(manifest.maps)) {
    imports.push(`import ${id}Original from '../${map.original.file}';`);
    const formats = [];
    for (const format of ['avif', 'webp']) {
      const variants = map.variants[format].map((variant) => {
        const name = `${id}${format}${variant.width}`;
        imports.push(`import ${name} from './${variant.file}';`);
        return `{ url: ${name}, width: ${variant.width} }`;
      });
      formats.push(`${format}: [${variants.join(', ')}]`);
    }
    entries.push(`  ${id}: { width: ${map.original.width}, height: ${map.original.height}, original: ${id}Original, ${formats.join(', ')} }`);
  }
  return `${imports.join('\n')}\n\nconst maps = {\n${entries.join(',\n')}\n};\nexport default maps;\n`;
}

function modernTransfers(manifest) {
  const result = { avifBytes: 0, webpBytes: 0, worstCaseBytes: 0 };
  for (const map of Object.values(manifest.maps)) {
    const avif = Math.max(...map.variants.avif.map((variant) => variant.bytes));
    const webp = Math.max(...map.variants.webp.map((variant) => variant.bytes));
    result.avifBytes += avif;
    result.webpBytes += webp;
    result.worstCaseBytes += Math.max(avif, webp);
  }
  return result;
}

async function generateMaps({ mapsDirectory = MAPS_DIRECTORY, maps = MAPS, budgetBytes = BUDGET_BYTES } = {}) {
  const output = path.join(mapsDirectory, 'generated');
  await fs.mkdir(output, { recursive: true });
  const manifest = { schemaVersion: 1, encoder: { sharp: sharp.versions.sharp, versions: sharp.versions, settings: SETTINGS }, maps: {} };
  for (const definition of maps) {
    const original = await fs.readFile(path.join(mapsDirectory, definition.file));
    if (definition.sha256 && sha256(original) !== definition.sha256) throw new Error(`Original master SHA256 changed: ${definition.file}`);
    const metadata = await sharp(original).metadata();
    if (metadata.width !== definition.width || metadata.height !== definition.height) throw new Error(`Master dimensions do not match: ${definition.file}`);
    const map = {
      original: { file: definition.file, width: metadata.width, height: metadata.height, bytes: original.length, sha256: sha256(original) },
      variants: { avif: [], webp: [] },
    };
    for (const format of ['avif', 'webp']) {
      for (const divisor of DIVISORS) {
        const width = definition.width / divisor;
        const height = definition.height / divisor;
        if (!Number.isInteger(width) || !Number.isInteger(height)) throw new Error(`Non-integral exact-ratio dimensions: ${definition.file}`);
        const file = `${definition.id}-${width}.${format}`;
        const bytes = await sharp(original).resize({ width, height, ...SETTINGS.resize })[format](SETTINGS[format]).toBuffer();
        await fs.writeFile(path.join(output, file), bytes);
        map.variants[format].push({ file, width, height, bytes: bytes.length, sha256: sha256(bytes) });
      }
    }
    manifest.maps[definition.id] = map;
  }
  manifest.coldModern = { budgetBytes, ...modernTransfers(manifest) };
  if (manifest.coldModern.worstCaseBytes > budgetBytes) throw new Error(`Cold modern map budget exceeded: ${manifest.coldModern.worstCaseBytes} > ${budgetBytes}`);
  await fs.writeFile(path.join(output, 'manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`);
  await fs.writeFile(path.join(output, 'sources.js'), sourceModule(manifest));
  return manifest;
}

if (require.main === module) generateMaps().then((manifest) => console.log(JSON.stringify(manifest.coldModern))).catch((error) => { console.error(error.message); process.exitCode = 1; });
module.exports = { generateMaps, modernTransfers, sourceModule, sha256, MAPS_DIRECTORY, MAPS, BUDGET_BYTES, DIVISORS, SETTINGS };
